document.addEventListener('DOMContentLoaded', () => {
  // 1. Initialize Icons
  if (window.lucide) {
    window.lucide.createIcons();
  }

  // 2. FAQ Accordion Interaction
  const faqItems = document.querySelectorAll('.faq-item');
  faqItems.forEach(item => {
    const btn = item.querySelector('.faq-question-btn');
    if (btn) {
      btn.addEventListener('click', () => {
        const isOpen = item.classList.contains('open');
        faqItems.forEach(other => other.classList.remove('open'));
        if (!isOpen) {
          item.classList.add('open');
        }
      });
    }
  });

  // 3. Smooth Anchor Scrolling & Active Nav Spy
  const navLinks = document.querySelectorAll('.nav-link');
  const sections = Array.from(document.querySelectorAll('section[id], div[id="showcase"]'));

  function updateActiveNav() {
    let current = '';
    const scrollPos = window.scrollY + 140;

    sections.forEach((sec, index) => {
      const top = sec.offsetTop;
      const next = sections[index + 1];
      const bottom = next ? next.offsetTop : document.documentElement.scrollHeight;
      if (scrollPos >= top && scrollPos < bottom) {
        current = sec.getAttribute('id');
      }
    });

    navLinks.forEach(link => {
      const isActive = link.getAttribute('href') === `#${current}`;
      link.classList.toggle('active', isActive);
    });
  }

  updateActiveNav();
  window.addEventListener('scroll', updateActiveNav, { passive: true });

  // 3b. Mobile Navigation Menu
  const mobileMenuBtn = document.getElementById('mobile-menu-trigger');
  const headerEl = document.querySelector('.header');

  if (mobileMenuBtn && headerEl) {
    const setMobileMenu = (open) => {
      headerEl.classList.toggle('mobile-menu-open', open);
      mobileMenuBtn.setAttribute('aria-expanded', String(open));
    };

    mobileMenuBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      setMobileMenu(!headerEl.classList.contains('mobile-menu-open'));
    });

    document.querySelectorAll('.nav-links a').forEach(link => {
      link.addEventListener('click', () => setMobileMenu(false));
    });

    document.addEventListener('click', (e) => {
      if (!headerEl.contains(e.target)) setMobileMenu(false);
    });

    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') setMobileMenu(false);
    });
  }

  // 4. Language Selector & Real-Time Full Site Translation
  const langToggleBtn = document.getElementById('lang-toggle-btn');
  const langMenu = document.getElementById('lang-menu');
  const langOptions = document.querySelectorAll('.lang-option');
  const currentFlagRing = document.querySelector('.active-flag-ring');

  function applyLanguage(lang) {
    if (!translations[lang]) return;

    // Set document direction and lang
    if (lang === 'ar') {
      document.documentElement.setAttribute('dir', 'rtl');
      document.documentElement.setAttribute('lang', 'ar');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
      document.documentElement.setAttribute('lang', lang);
    }

    // Update all elements with data-i18n
    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // Update active state in menu
    langOptions.forEach(opt => {
      if (opt.getAttribute('data-lang') === lang) {
        opt.classList.add('active');
        const flagSvg = opt.querySelector('.flag-icon');
        if (flagSvg && currentFlagRing) {
          currentFlagRing.innerHTML = flagSvg.outerHTML;
        }
      } else {
        opt.classList.remove('active');
      }
    });

    // Refresh icons
    if (window.lucide) {
      window.lucide.createIcons();
    }

    localStorage.setItem('thryn_preferred_lang', lang);
  }

  if (langToggleBtn && langMenu) {
    langToggleBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const isOpen = langMenu.classList.contains('open');
      langMenu.classList.toggle('open', !isOpen);
      langToggleBtn.setAttribute('aria-expanded', !isOpen);
    });

    // Close when clicking outside
    document.addEventListener('click', (e) => {
      if (!langMenu.contains(e.target) && !langToggleBtn.contains(e.target)) {
        langMenu.classList.remove('open');
        langToggleBtn.setAttribute('aria-expanded', 'false');
      }
    });

    // Language selection click
    langOptions.forEach(opt => {
      opt.addEventListener('click', () => {
        const selectedLang = opt.getAttribute('data-lang');
        applyLanguage(selectedLang);
        langMenu.classList.remove('open');
        langToggleBtn.setAttribute('aria-expanded', 'false');
      });
    });
  }

  // Restore saved language preference or default to Arabic
  const savedLang = localStorage.getItem('thryn_preferred_lang');
  if (savedLang && translations[savedLang]) {
    applyLanguage(savedLang);
  }

  // 5. User Account Auth & Profile Dropdown Engine
  const navLoginBtn = document.getElementById('nav-login-btn');
  const navUserWrapper = document.getElementById('nav-user-wrapper');
  const navAvatarBtn = document.getElementById('nav-avatar-btn');
  const navAvatarImg = document.getElementById('nav-avatar-img');
  const navUserDropdown = document.getElementById('nav-user-dropdown');
  const navUserLogoutBtn = document.getElementById('nav-user-logout-btn');
  const navUserLangToggle = document.getElementById('nav-user-lang-toggle');
  const navUserLangLabel = document.getElementById('nav-user-lang-label');
  const navUserLangFlag = document.getElementById('nav-user-lang-flag');

  const langNames = {
    ar: "العربية",
    en: "English",
    fr: "Français",
    tr: "Türkçe"
  };

  const langFlags = {
    ar: "🇸🇦",
    en: "🇺🇸",
    fr: "🇫🇷",
    tr: "🇹🇷"
  };

  function updateNavAuthState() {
    let user = null;
    try {
      user = JSON.parse(localStorage.getItem('thryn_discord_user') || 'null');
    } catch(e) {}

    if (user && user.isLoggedIn && user.username) {
      if (navLoginBtn) navLoginBtn.style.display = 'none';
      if (navUserWrapper) navUserWrapper.style.display = 'inline-flex';
      if (navAvatarImg) {
        navAvatarImg.src = user.avatar || 'assets/probot/user_avatar.png';
      }
    } else {
      if (navLoginBtn) navLoginBtn.style.display = 'inline-flex';
      if (navUserWrapper) navUserWrapper.style.display = 'none';
      if (navUserDropdown) navUserDropdown.classList.remove('open');
    }
  }

  function updateDropdownLangDisplay(lang) {
    if (navUserLangLabel) navUserLangLabel.textContent = langNames[lang] || 'English';
    if (navUserLangFlag) navUserLangFlag.textContent = langFlags[lang] || '🇺🇸';
  }

  if (navAvatarBtn && navUserDropdown) {
    navAvatarBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const isOpen = navUserDropdown.classList.contains('open');
      navUserDropdown.classList.toggle('open', !isOpen);
      navAvatarBtn.setAttribute('aria-expanded', !isOpen);
    });

    document.addEventListener('click', (e) => {
      if (!navUserDropdown.contains(e.target) && !navAvatarBtn.contains(e.target)) {
        navUserDropdown.classList.remove('open');
        navAvatarBtn.setAttribute('aria-expanded', 'false');
      }
    });
  }

  if (navUserLogoutBtn) {
    navUserLogoutBtn.addEventListener('click', () => {
      try {
        localStorage.removeItem('thryn_discord_user');
      } catch(e) {}
      updateNavAuthState();
    });
  }

  if (navUserLangToggle) {
    navUserLangToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      const current = localStorage.getItem('thryn_preferred_lang') || 'ar';
      const order = ['ar', 'en', 'fr', 'tr'];
      const nextIdx = (order.indexOf(current) + 1) % order.length;
      const nextLang = order[nextIdx];
      applyLanguage(nextLang);
      updateDropdownLangDisplay(nextLang);
    });
  }

  // Hook into applyLanguage to sync dropdown language label
  const originalApplyLanguage = applyLanguage;
  applyLanguage = function(lang) {
    originalApplyLanguage(lang);
    updateDropdownLangDisplay(lang);
  };

  // Expose login helper for testing or direct auth
  window.loginWithDiscord = function(userObj) {
    const user = {
      username: (userObj && userObj.username) || 'Fragment',
      avatar: (userObj && userObj.avatar) || 'assets/probot/user_avatar.png',
      discordId: (userObj && userObj.id) || '109284918293',
      isLoggedIn: true
    };
    try {
      localStorage.setItem('thryn_discord_user', JSON.stringify(user));
    } catch(e) {}
    updateNavAuthState();
  };

  updateNavAuthState();
  updateDropdownLangDisplay(localStorage.getItem('thryn_preferred_lang') || 'ar');
});
